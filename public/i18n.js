const DICTS = { en, bn };
const STORAGE_KEY = "lang";

function readStoredLang() {
  try {
    return globalThis.localStorage?.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

let current = readStoredLang() === "bn" ? "bn" : "en";

export function getLang() {
  return current;
}

export function hasKey(key) {
  return key in en;
}

export function t(key, vars) {
  const template = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : ""));
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  document.documentElement.lang = current;
}

const listeners = new Set();
export function onLangChange(fn) {
  listeners.add(fn);
}

export function setLang(lang) {
  current = lang === "bn" ? "bn" : "en";
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, current);
  } catch {
    // storage blocked: the choice lasts for this page view
  }
  applyI18n();
  for (const fn of listeners) fn(current);
}

export function brandName() {
  return globalThis.window?.APP_CONFIG?.BRAND_NAME || "Boltpage";
}

export { en as EN_STRINGS, bn as BN_STRINGS };

// Page bootstrap: translate static markup, fill brand name, wire language toggles.
if (typeof document !== "undefined") {
  applyI18n();
  for (const el of document.querySelectorAll("[data-brand]")) el.textContent = brandName();
  for (const btn of document.querySelectorAll("[data-lang-toggle]")) {
    btn.addEventListener("click", () => setLang(current === "en" ? "bn" : "en"));
  }
}
